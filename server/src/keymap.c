/* RDPServer: scancodes to RISC OS low-level key numbers. See keymap.h.

   RDP sends the key's position (PC/AT scancode set 1), not the character,
   so the layout is RISC OS's own: with RISC OS set to a UK keyboard, the
   key left of Z (scancode &56) is \ | and the key left of Return (&2B)
   is # ~, as on a RiscPC.

   Copyright (c) 2026 Andrew Youll. MIT licence (see LICENSE). */
#include "keymap.h"

/* Plain scancodes &00-&7F. -1: none. */
static const signed char plain[128] =
{
  /* &00 */ -1, 0x00, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16,
  /* &08 */ 0x17, 0x18, 0x19, 0x1A, 0x1B, 0x1C, 0x1E, 0x26,
  /* &10 */ 0x27, 0x28, 0x29, 0x2A, 0x2B, 0x2C, 0x2D, 0x2E,
  /* &18 */ 0x2F, 0x30, 0x31, 0x32, 0x47, 0x3B, 0x3C, 0x3D,
  /* &20 */ 0x3E, 0x3F, 0x40, 0x41, 0x42, 0x43, 0x44, 0x45,
  /* &28 */ 0x46, 0x10, 0x4C, 0x33, 0x4E, 0x4F, 0x50, 0x51,
  /* &30 */ 0x52, 0x53, 0x54, 0x55, 0x56, 0x57, 0x58, 0x24,
  /* &38 */ 0x5E, 0x5F, 0x5D, 0x01, 0x02, 0x03, 0x04, 0x05,
  /* &40 */ 0x06, 0x07, 0x08, 0x09, 0x0A, 0x22, 0x0E, 0x37,
  /* &48 */ 0x38, 0x39, 0x3A, 0x48, 0x49, 0x4A, 0x4B, 0x5A,
  /* &50 */ 0x5B, 0x5C, 0x65, 0x66, -1, -1, 0x4D, 0x0B,
  /* &58 */ 0x0C, -1, -1, -1, -1, -1, -1, -1,
  /* &60 */ -1, -1, -1, -1, -1, -1, -1, -1,
  /* &68 */ -1, -1, -1, -1, -1, -1, -1, -1,
  /* &70 */ 0x6D, -1, -1, 0x6E, -1, -1, -1, -1,
  /* &78 */ -1, 0x6C, -1, 0x6B, -1, -1, -1, -1
};

int
keymap_lookup (int scancode, int extended)
{
  if (scancode < 0 || scancode > 127)
    return -1;
  if (!extended)
    return plain[scancode];
  switch (scancode)
    {
    case 0x1C: return 0x67;   /* keypad Enter */
    case 0x1D: return 0x61;   /* right Ctrl */
    case 0x35: return 0x23;   /* keypad / */
    case 0x37: return 0x0D;   /* Print Screen */
    case 0x38: return 0x60;   /* right Alt (AltGr) */
    case 0x45: return 0x0F;   /* Pause (sent as extended NumLock) */
    case 0x46: return 0x0F;   /* Break (Ctrl-Pause) */
    case 0x47: return 0x20;   /* Home */
    case 0x48: return 0x59;   /* Up */
    case 0x49: return 0x21;   /* Page Up */
    case 0x4B: return 0x62;   /* Left */
    case 0x4D: return 0x64;   /* Right */
    case 0x4F: return 0x35;   /* End (Copy) */
    case 0x50: return 0x63;   /* Down */
    case 0x51: return 0x36;   /* Page Down */
    case 0x52: return 0x1F;   /* Insert */
    case 0x53: return 0x34;   /* Delete */
    case 0x5B: return 0x68;   /* left Windows */
    case 0x5C: return 0x69;   /* right Windows */
    case 0x5D: return 0x6A;   /* Menu */
    default: return -1;
    }
}
